import AVFoundation
import CoreText
import Foundation

/// A synthetic, copyright-free demo: two Tang poems in their original Chinese, each line paired
/// with its traditional Japanese kundoku reading (書き下し), burnt into a short video over a
/// generated soundtrack. The poems are public domain and kundoku is a conventional reading, not
/// anyone's translation. `sample` also writes a second copy of the audio that starts 5 seconds
/// later and plays slightly faster, to show how subtitles move onto another recording.
enum SampleSpec {
    struct Line: Codable, Equatable {
        let start: Double
        let end: Double
        let zh: String
        let ja: String
    }

    static let width = 1280
    static let height = 720
    static let fps: Int32 = 25
    static let duration = 40.0
    static let audioRate = 44_100

    /// Seconds cut from the start of the second recording, and how much faster it plays.
    static let trim = 5.0
    static let speed = 1.008

    static let credit = "原诗：孟浩然《春晓》 王之涣《登鹳雀楼》"
    static let creditStart = 0.5
    static let creditEnd = 4.5

    static let lines: [Line] = {
        let text: [(String, String)] = [
            ("春眠不觉晓", "春眠暁を覚えず"),
            ("处处闻啼鸟", "処処に啼鳥を聞く"),
            ("夜来风雨声", "夜来風雨の声"),
            ("花落知多少", "花落つること知る多少"),
            ("白日依山尽", "白日山に依りて尽き"),
            ("黄河入海流", "黄河海に入りて流る"),
            ("欲穷千里目", "千里の目を窮めんと欲して"),
            ("更上一层楼", "更に上る一層の楼")
        ]
        return text.enumerated().map { index, pair in
            let start = 6.0 + Double(index) * 4
            return Line(start: start, end: start + 3.6, zh: pair.0, ja: pair.1)
        }
    }()

    static let template = Template(regions: [
        Region(id: "zh", language: "zh-Hans", x: 0.06, y: 0.70, width: 0.6, height: 0.075,
               brightTextThreshold: 170, ocrBrightnessThreshold: 140, ignorePrefixes: ["原诗："]),
        Region(id: "ja", language: "ja-JP", x: 0.06, y: 0.785, width: 0.6, height: 0.065,
               brightTextThreshold: 170, ocrBrightnessThreshold: 140)
    ])

    /// Where a moment of the video falls in the second recording.
    static func otherTime(_ videoTime: Double) -> Double { (videoTime - trim) / speed }
}

func writeSample(to output: URL) async throws {
    log(L("生成合成音频…", "Synthesizing audio…"))
    let audio = synthesizeSoundtrack(seconds: SampleSpec.duration, rate: SampleSpec.audioRate)
    log(L("生成示例视频…", "Rendering the sample video…"))
    try await writeSampleVideo(audio: audio, to: output.appendingPathComponent("sample.mp4"))
    try writeWAV(shiftedCopy(audio), rate: SampleSpec.audioRate, to: output.appendingPathComponent("other-master.wav"))
    try writeJSON(SampleSpec.template, to: output.appendingPathComponent("template.json"))

    struct Truth: Encodable {
        let note: String
        let credit: String
        let lines: [SampleSpec.Line]
    }
    try writeJSON(Truth(note: "Video timeline. Generated by `lyrics-ocr sample`.",
                        credit: SampleSpec.credit, lines: SampleSpec.lines),
                  to: output.appendingPathComponent("truth.json"))

    // Reference lyrics on the second recording's timeline, for --lrc and check --reference.
    let reference = SampleSpec.lines.map { line -> String in
        let cs = Int((SampleSpec.otherTime(line.start) * 100).rounded())
        return String(format: "[%02d:%02d.%02d]", cs / 6000, cs / 100 % 60, cs % 100) + line.ja + "\n"
    }.joined()
    try writeText(reference, to: output.appendingPathComponent("reading.lrc"))
}

// MARK: - Audio

/// A deterministic, non-repeating melody with a soft noise bed, so that matching points are unambiguous.
func synthesizeSoundtrack(seconds: Double, rate: Int) -> [Float] {
    var random = SplitMix(seed: 0x5EED_1A7E)
    let count = Int(seconds * Double(rate))
    var samples = [Float](repeating: 0, count: count)
    let scale = [0, 3, 5, 7, 10, 12, 15, 17].map { 220 * pow(2, Double($0) / 12) }

    var time = 0.2
    while time < seconds - 0.2 {
        let length = 0.12 + 0.33 * random.unit()
        let frequency = scale[Int(random.next() % UInt64(scale.count))] * (random.unit() < 0.3 ? 2 : 1)
        let loudness = 0.18 + 0.12 * random.unit()
        let first = Int(time * Double(rate))
        let last = min(count, Int((time + length + 0.25) * Double(rate)))
        for index in first..<last {
            let t = Double(index - first) / Double(rate)
            let envelope = min(1, t / 0.01) * exp(-t * (3 + 4 * (1 - length)))
            let phase = 2 * Double.pi * frequency * t
            let tone = sin(phase) + 0.4 * sin(2 * phase) + 0.15 * sin(3 * phase)
            samples[index] += Float(loudness * envelope * tone)
        }
        if random.unit() < 0.18 {
            // A short percussive burst.
            for index in first..<min(count, first + rate / 20) {
                let t = Double(index - first) / Double(rate)
                samples[index] += Float(0.25 * exp(-t * 60) * (random.unit() * 2 - 1))
            }
        }
        time += length
    }
    var low: Float = 0
    for index in samples.indices {
        low = 0.98 * low + 0.02 * Float(random.unit() * 2 - 1)
        samples[index] = max(-1, min(1, samples[index] + 0.06 * low))
    }
    return samples
}

/// The same audio, starting `trim` seconds later and played `speed` times faster.
private func shiftedCopy(_ audio: [Float]) -> [Float] {
    let rate = Double(SampleSpec.audioRate)
    let count = Int((Double(audio.count) / rate - SampleSpec.trim) / SampleSpec.speed * rate)
    return (0..<count).map { index in
        let position = (SampleSpec.trim + Double(index) / rate * SampleSpec.speed) * rate
        let floor = Int(position)
        guard floor + 1 < audio.count else { return 0 }
        let fraction = Float(position - Double(floor))
        return audio[floor] + fraction * (audio[floor + 1] - audio[floor])
    }
}

private func writeWAV(_ samples: [Float], rate: Int, to url: URL) throws {
    let settings: [String: Any] = [
        AVFormatIDKey: kAudioFormatLinearPCM, AVSampleRateKey: rate, AVNumberOfChannelsKey: 1,
        AVLinearPCMBitDepthKey: 16, AVLinearPCMIsFloatKey: false, AVLinearPCMIsBigEndianKey: false
    ]
    let file = try AVAudioFile(forWriting: url, settings: settings, commonFormat: .pcmFormatFloat32, interleaved: false)
    guard let buffer = AVAudioPCMBuffer(pcmFormat: file.processingFormat, frameCapacity: AVAudioFrameCount(samples.count)) else {
        throw Failure(L("无法创建音频缓冲。", "Could not create an audio buffer."))
    }
    buffer.frameLength = AVAudioFrameCount(samples.count)
    samples.withUnsafeBufferPointer { source in
        buffer.floatChannelData![0].update(from: source.baseAddress!, count: samples.count)
    }
    try file.write(from: buffer)
}

private struct SplitMix {
    var state: UInt64
    init(seed: UInt64) { state = seed }
    mutating func next() -> UInt64 {
        state &+= 0x9E37_79B9_7F4A_7C15
        var z = state
        z = (z ^ (z >> 30)) &* 0xBF58_476D_1CE4_E5B9
        z = (z ^ (z >> 27)) &* 0x94D0_49BB_1331_11EB
        return z ^ (z >> 31)
    }
    mutating func unit() -> Double { Double(next() >> 11) / Double(1 << 53) }
}

// MARK: - Video

private func writeSampleVideo(audio: [Float], to url: URL) async throws {
    let writer = try AVAssetWriter(outputURL: url, fileType: .mp4)
    let video = AVAssetWriterInput(mediaType: .video, outputSettings: [
        AVVideoCodecKey: AVVideoCodecType.h264,
        AVVideoWidthKey: SampleSpec.width,
        AVVideoHeightKey: SampleSpec.height,
        AVVideoCompressionPropertiesKey: [AVVideoAverageBitRateKey: 3_000_000]
    ])
    let sound = AVAssetWriterInput(mediaType: .audio, outputSettings: [
        AVFormatIDKey: kAudioFormatMPEG4AAC, AVSampleRateKey: SampleSpec.audioRate,
        AVNumberOfChannelsKey: 1, AVEncoderBitRateKey: 128_000
    ])
    video.expectsMediaDataInRealTime = false
    sound.expectsMediaDataInRealTime = false
    let adaptor = AVAssetWriterInputPixelBufferAdaptor(assetWriterInput: video, sourcePixelBufferAttributes: [
        kCVPixelBufferPixelFormatTypeKey as String: kCVPixelFormatType_32BGRA,
        kCVPixelBufferWidthKey as String: SampleSpec.width,
        kCVPixelBufferHeightKey as String: SampleSpec.height
    ])
    guard writer.canAdd(video), writer.canAdd(sound) else {
        throw Failure(L("无法设置视频编码。", "Could not set up video encoding."))
    }
    writer.add(video)
    writer.add(sound)
    guard writer.startWriting() else {
        throw writer.error ?? Failure(L("无法写入示例视频。", "Could not write the sample video."))
    }
    writer.startSession(atSourceTime: .zero)

    var format = AudioStreamBasicDescription(
        mSampleRate: Double(SampleSpec.audioRate), mFormatID: kAudioFormatLinearPCM,
        mFormatFlags: kAudioFormatFlagIsFloat | kAudioFormatFlagIsPacked, mBytesPerPacket: 4,
        mFramesPerPacket: 1, mBytesPerFrame: 4, mChannelsPerFrame: 1, mBitsPerChannel: 32, mReserved: 0)
    var description: CMAudioFormatDescription?
    CMAudioFormatDescriptionCreate(allocator: nil, asbd: &format, layoutSize: 0, layout: nil,
                                   magicCookieSize: 0, magicCookie: nil, extensions: nil,
                                   formatDescriptionOut: &description)
    guard let description else { throw Failure(L("无法设置音频格式。", "Could not set up the audio format.")) }

    let frames = Int(SampleSpec.duration * Double(SampleSpec.fps))
    let chunk = SampleSpec.audioRate / 10
    var audioPosition = 0
    let renderer = FrameRenderer()

    func wait(for input: AVAssetWriterInput) throws {
        while !input.isReadyForMoreMediaData {
            if writer.status == .failed { throw writer.error ?? Failure(L("视频编码失败。", "Video encoding failed.")) }
            usleep(2_000)
        }
    }

    for frame in 0..<frames {
        let time = Double(frame) / Double(SampleSpec.fps)
        // Keep the two tracks interleaved: feed audio up to half a second past this frame.
        while audioPosition < audio.count, Double(audioPosition) / Double(SampleSpec.audioRate) < time + 0.5 {
            let count = min(chunk, audio.count - audioPosition)
            try wait(for: sound)
            let buffer = try audioBuffer(Array(audio[audioPosition..<(audioPosition + count)]),
                                         at: audioPosition, format: description)
            guard sound.append(buffer) else {
                throw writer.error ?? Failure(L("音频编码失败。", "Audio encoding failed."))
            }
            audioPosition += count
        }
        try wait(for: video)
        guard let pool = adaptor.pixelBufferPool else {
            throw writer.error ?? Failure(L("视频编码失败。", "Video encoding failed."))
        }
        var pixels: CVPixelBuffer?
        CVPixelBufferPoolCreatePixelBuffer(nil, pool, &pixels)
        guard let pixels else { throw Failure(L("视频编码失败。", "Video encoding failed.")) }
        renderer.draw(time: time, into: pixels)
        guard adaptor.append(pixels, withPresentationTime: CMTime(value: CMTimeValue(frame), timescale: SampleSpec.fps)) else {
            throw writer.error ?? Failure(L("视频编码失败。", "Video encoding failed."))
        }
    }
    video.markAsFinished()
    sound.markAsFinished()
    await writer.finishWriting()
    if writer.status != .completed {
        throw writer.error ?? Failure(L("无法写入示例视频。", "Could not write the sample video."))
    }
}

private func audioBuffer(_ samples: [Float], at position: Int, format: CMAudioFormatDescription) throws -> CMSampleBuffer {
    let length = samples.count * 4
    var block: CMBlockBuffer?
    CMBlockBufferCreateWithMemoryBlock(allocator: nil, memoryBlock: nil, blockLength: length, blockAllocator: nil,
                                       customBlockSource: nil, offsetToData: 0, dataLength: length,
                                       flags: kCMBlockBufferAssureMemoryNowFlag, blockBufferOut: &block)
    guard let block else { throw Failure(L("音频编码失败。", "Audio encoding failed.")) }
    let status = samples.withUnsafeBytes { bytes in
        CMBlockBufferReplaceDataBytes(with: bytes.baseAddress!, blockBuffer: block, offsetIntoDestination: 0, dataLength: length)
    }
    var buffer: CMSampleBuffer?
    let made = CMAudioSampleBufferCreateReadyWithPacketDescriptions(
        allocator: nil, dataBuffer: block, formatDescription: format, sampleCount: samples.count,
        presentationTimeStamp: CMTime(value: CMTimeValue(position), timescale: CMTimeScale(SampleSpec.audioRate)),
        packetDescriptions: nil, sampleBufferOut: &buffer)
    guard status == kCMBlockBufferNoErr, made == noErr, let buffer else {
        throw Failure(L("音频编码失败。", "Audio encoding failed."))
    }
    return buffer
}

private final class FrameRenderer {
    private let space = CGColorSpace(name: CGColorSpace.sRGB)!
    private let lyricFont = CTFontCreateWithName("PingFangSC-Medium" as CFString, 40, nil)
    private let readingFont = CTFontCreateWithName("HiraginoSans-W5" as CFString, 32, nil)
    private let creditFont = CTFontCreateWithName("PingFangSC-Regular" as CFString, 30, nil)

    func draw(time: Double, into pixels: CVPixelBuffer) {
        CVPixelBufferLockBaseAddress(pixels, [])
        defer { CVPixelBufferUnlockBaseAddress(pixels, []) }
        let width = SampleSpec.width, height = SampleSpec.height
        guard let context = CGContext(
            data: CVPixelBufferGetBaseAddress(pixels), width: width, height: height, bitsPerComponent: 8,
            bytesPerRow: CVPixelBufferGetBytesPerRow(pixels), space: space,
            bitmapInfo: CGImageAlphaInfo.premultipliedFirst.rawValue | CGBitmapInfo.byteOrder32Little.rawValue
        ) else { return }

        // A slowly drifting dark background, so frames are not trivially identical.
        context.setFillColor(CGColor(red: 0.05, green: 0.06, blue: 0.11, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        for index in 0..<4 {
            let phase = time * (0.07 + 0.03 * Double(index)) + Double(index) * 1.7
            let center = CGPoint(x: Double(width) * (0.5 + 0.4 * sin(phase)),
                                 y: Double(height) * (0.55 + 0.35 * cos(phase * 1.3)))
            let radius = 160.0 + 40 * Double(index)
            context.setFillColor(CGColor(red: 0.16, green: 0.20 + 0.04 * Double(index), blue: 0.32, alpha: 0.35))
            context.fillEllipse(in: CGRect(x: center.x - radius, y: center.y - radius, width: radius * 2, height: radius * 2))
        }

        let left = Double(width) * 0.08
        if let line = SampleSpec.lines.first(where: { time >= $0.start && time < $0.end }) {
            let alpha = fade(time, start: line.start, end: line.end)
            text(line.zh, font: lyricFont, x: left, centerFromTop: Double(height) * 0.7375, alpha: alpha, in: context)
            text(line.ja, font: readingFont, x: left, centerFromTop: Double(height) * 0.8175, alpha: alpha, in: context)
        } else if time >= SampleSpec.creditStart, time < SampleSpec.creditEnd {
            text(SampleSpec.credit, font: creditFont, x: left, centerFromTop: Double(height) * 0.7375,
                 alpha: fade(time, start: SampleSpec.creditStart, end: SampleSpec.creditEnd), in: context)
        }
    }

    private func fade(_ time: Double, start: Double, end: Double) -> Double {
        min(1, (time - start) / 0.12 + 0.34, (end - time) / 0.12 + 0.34)
    }

    private func text(_ string: String, font: CTFont, x: Double, centerFromTop: Double, alpha: Double, in context: CGContext) {
        let attributes: [NSAttributedString.Key: Any] = [
            NSAttributedString.Key(kCTFontAttributeName as String): font,
            NSAttributedString.Key(kCTForegroundColorAttributeName as String): CGColor(red: 1, green: 1, blue: 1, alpha: alpha)
        ]
        let line = CTLineCreateWithAttributedString(NSAttributedString(string: string, attributes: attributes))
        var ascent: CGFloat = 0, descent: CGFloat = 0, leading: CGFloat = 0
        _ = CTLineGetTypographicBounds(line, &ascent, &descent, &leading)
        let baseline = Double(SampleSpec.height) - centerFromTop - Double(ascent - descent) / 2
        context.saveGState()
        context.setShadow(offset: CGSize(width: 0, height: -2), blur: 3,
                          color: CGColor(red: 0, green: 0, blue: 0, alpha: 0.8 * alpha))
        context.textPosition = CGPoint(x: x, y: baseline)
        CTLineDraw(line, context)
        context.restoreGState()
    }
}
